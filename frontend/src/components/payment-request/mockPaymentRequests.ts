import type { PaymentAttempt, PaymentRequest } from "../../types/paymentRequest";
import { normalizeRequest } from "./paymentRequestUtils";

function attempt(data: Omit<PaymentAttempt, "id">): PaymentAttempt {
  return { id: `${data.code}-${data.idx}`, ...data };
}

function request(data: Omit<PaymentRequest, "received" | "doneCount" | "totalCount" | "delta" | "state">): PaymentRequest {
  return normalizeRequest({ ...data, received: 0, doneCount: 0, totalCount: 0, delta: 0, state: "pending" });
}

